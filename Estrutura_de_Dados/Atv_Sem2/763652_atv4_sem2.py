def correct_readings(original_readings):
    corrected_readings = list(original_readings)
    corrected_indices = []

    def _find_valid_left(arr, index):
        for j in range(index - 1, -1, -1):
            if arr[j] != -1:
                return arr[j]
        return None

    def _find_valid_right(arr, index):
        for j in range(index + 1, len(arr)):
            if arr[j] != -1:
                return arr[j]
        return None

    for i, val in enumerate(corrected_readings):
        if val == -1:
            corrected_indices.append(i);

            left_val = _find_valid_left(corrected_readings, i)
            right_val = _find_valid_right(corrected_readings, i)

            if i == 0:
                if right_val is not None:
                    corrected_readings[i] = right_val
            elif i == len(corrected_readings) - 1:
                if left_val is not None:
                    corrected_readings[i] = left_val
            else:
                if left_val is not None and right_val is not None:
                    corrected_readings[i] = (left_val + right_val) / 2
                elif left_val is not None:
                    corrected_readings[i] = left_val
                elif right_val is not None:
                    corrected_readings[i] = right_val

    return corrected_readings, corrected_indices

leituras = [18.4, -1, 19.0, 20.1, -1, 21.0]

leituras_corrigidas, indices_corrigidos = correct_readings(leituras)

print(f"Sequência original: {leituras}")
print(f"Sequência corrigida: {leituras_corrigidas}")
print(f"Índices que precisaram ser corrigidos: {indices_corrigidos}")