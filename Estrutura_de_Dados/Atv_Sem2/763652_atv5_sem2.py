agenda = ["Ana", "Bruno", "Carla", "Diego", "Elisa", "Fábio"]
cancelled_index = 2

print("Agenda antes da alteração:")
print(agenda)


for i in range(cancelled_index, len(agenda) - 1):
    print(f"Deslocando '{agenda[i+1]}' da posição {i+1} para a posição {i}")
    agenda[i] = agenda[i+1]
    print(f"Estado atual da agenda: {agenda}")

agenda[len(agenda) - 1] = "LIVRE"
print(f"\nPreenchendo a última posição com 'LIVRE'.\nEstado atual da agenda: {agenda}")


print("\nAgenda depois da alteração:")
print(agenda)