base_address = 4096
num_elements = 7
element_size = 8

address_to_validate = 4128

print(f"Endereço base da estrutura: {base_address}")
print(f"Número de elementos: {num_elements}")
print(f"Tamanho de cada elemento: {element_size} bytes")
print(f"Endereço informado para validação: {address_to_validate}\n")

initial_address = base_address

total_bytes = num_elements * element_size

last_element_start_address = initial_address + (num_elements - 1) * element_size
last_element_end_address = last_element_start_address + element_size - 1

print(f"Endereço inicial da estrutura: {initial_address}")
print(f"Endereço do início do último elemento: {last_element_start_address}")
print(f"Endereço do último byte do último elemento: {last_element_end_address}")
print(f"Total de bytes ocupados pelo vetor: {total_bytes}\n")

is_in_range = (address_to_validate >= initial_address) and (address_to_validate <= last_element_end_address)

is_aligned = (address_to_validate - initial_address) % element_size == 0

index = -1
if is_in_range and is_aligned:
    index = (address_to_validate - initial_address) // element_size
    if not (0 <= index < num_elements):
        is_in_range = False


print(f"O endereço {address_to_validate} está dentro da faixa ocupada pelo vetor? {is_in_range}")
print(f"O endereço {address_to_validate} está corretamente alinhado ao tamanho de {element_size} bytes? {is_aligned}")
print("\nResultado da Auditoria:")

if is_in_range and is_aligned:
    print(f"O endereço {address_to_validate} é válido e corresponde ao índice: {index}")
elif not is_in_range:
    print(f"O endereço {address_to_validate} é inválido: está fora da faixa ocupada pelo vetor (de {initial_address} a {last_element_end_address}).")
elif not is_aligned:
    print(f"O endereço {address_to_validate} é inválido: está desalinhado ao tamanho de {element_size} bytes.")
else:
    print(f"O endereço {address_to_validate} é inválido por uma razão desconhecida.")