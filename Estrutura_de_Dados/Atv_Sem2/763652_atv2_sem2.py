codigos = [4102, 5178, 6301, 7420, 8555, 9604]


codigo_procurado = 7420


ENDERECO_INICIAL = 12000
TAMANHO_BYTE = 4


indice_encontrado = -1

for i in range(len(codigos)):
    if codigos[i] == codigo_procurado:
        indice_encontrado = i
        break
if indice_encontrado != -1:

    endereco_estimado = ENDERECO_INICIAL + (indice_encontrado * TAMANHO_BYTE)


    print("=== Livro Localizado com Sucesso ===")
    print(f"• Código localizado: {codigo_procurado}")
    print(f"• Índice ocupado: {indice_encontrado}")
    print(f"• Endereço estimado: {endereco_estimado}")
else:
    print(f"O código {codigo_procurado} não foi encontrado na biblioteca.")