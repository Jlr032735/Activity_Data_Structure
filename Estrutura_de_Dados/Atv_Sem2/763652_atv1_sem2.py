temperaturas = [21.4, 22.1, 24.8, 23.0, 22.6, 25.2, 26.0, 24.5]

indice_1 = 0
indice_2 = 1

maior_variacao = abs (temperaturas[1] - temperaturas[0])

for i in range(1, len(temperaturas)):
  variacao_atual = abs (temperaturas[i] - temperaturas [i - 1])

if variacao_atual > maior_variacao:
  maior_variacao = variacao_atual
  indice_1 = i - 1
  indice_2 = i

  valor_inicial = temperaturas[indice_1]
  valor_final = temperaturas[indice_2]

if valor_final > valor_inicial:
    tipo_variacao = "Aumento"
elif valor_final < valor_inicial:
  tipo_variacao = "Queda"
else:
  tipo_variacao = "Sem alteração"

print("=== Relatório de Maior Variação de Temperatura ===")
print(f"• Índices envolvidos: {indice_1} e {indice_2}")
print(
    f"• Valores registrados: Índice {indice_1} = {valor_inicial}°C | Índice {indice_2} = {valor_final}°C"
)
print(f"• Magnitude da variação: {maior_variacao:.1f}°C")
print(f"• Comportamento: {tipo_variacao} de temperatura")