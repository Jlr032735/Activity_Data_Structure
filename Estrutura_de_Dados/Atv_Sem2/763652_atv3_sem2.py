setores = [
    "Recepção",
    "UTI",
    "Centro Cirúrgico",
    "Pediatria",
    "Laboratório",
    "Enfermaria"
]
quantidades = [18, 6, 14, 3, 11, 9]


min_quantidade = min(quantidades)
min_indice = quantidades.index(min_quantidade)
setor_menor_quantidade = setores[min_indice]


max_quantidade = max(quantidades)
max_indice = quantidades.index(max_quantidade)
setor_maior_quantidade = setores[max_indice]


diferenca_estoque = max_quantidade - min_quantidade


print(f"Setor com a menor quantidade disponível: {setor_menor_quantidade}")
print(f"Quantidade mínima: {min_quantidade}")
print(f"Índice do setor com menor quantidade: {min_indice}\n")

print(f"Setor com a maior quantidade disponível: {setor_maior_quantidade}")
print(f"Quantidade máxima: {max_quantidade}")
print(f"Índice do setor com maior quantidade: {max_indice}\n")

print(f"Diferença entre o maior e o menor estoque: {diferenca_estoque}")